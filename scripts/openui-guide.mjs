// Writes src/core/openui-guide.ts (ADR 0118): OpenUI's own guide to OpenUI Lang for the components the
// vendored bundle draws, with Owni's opening and rules in place of the ones meant for a whole-page app.
// OpenUI is not a dependency of Owni, so this runs in a folder of its own, with the versions the
// bundle in src/web/openui was built from (browser-bundle 0.2.1: react-ui 0.18, lang-core 1.0):
//
//   cd "$(mktemp -d)"
//   npm i @openuidev/react-ui@0.18.1 @openuidev/lang-core@1.0.1 react@19 react-dom@19 zod@4
//   cp "<owni>/scripts/openui-guide.mjs" . && node openui-guide.mjs "<owni>/src/core/openui-guide.ts"
import { writeFileSync } from "node:fs";
import { generateSystemPrompt } from "@openuidev/lang-core";
import { openuiChatLibrary, openuiChatPromptOptions } from "@openuidev/react-ui/genui-lib";

const out = process.argv[2];
if (!out) throw new Error("usage: node openui-guide.mjs <path of src/core/openui-guide.ts>");

const preamble = [
	"# Interactive answers in the console (OpenUI Lang)",
	"",
	"In a console conversation a reply may include ONE interactive block: OpenUI Lang code in a fenced block that opens with ```openui-lang and closes with ```. The console draws it as a live interface inside the reply; any text before or after the block shows as ordinary chat. Each block is a whole program on its own: never a patch of an earlier one.",
	"",
	"Use it only when it serves the person better than prose or a Markdown table: figures to compare in a chart or KPI cards, a choice among options to click, a short form to collect the details of a request. For an explanation, a short answer or a plain list, write text. For a standalone page to keep open (a dashboard, a report, a calculator) use an artifact instead.",
	"",
	"Rules of Owni that come before everything below:",
	"- Never invent data. Every number, name, date and amount comes from the conversation, a file or a tool result; with no data, ask or say so in text.",
	"- Write every label, title and option in the person's language (Italian unless they write in another).",
	"- Pictures from the web do not load in the block: do not use Image, ImageBlock, ImageGallery or any image slot.",
	"- A button with @ToAssistant, or a form's submit, writes the person's next message in their box, for them to read and send: the words of the action, the values filled in, and its context. Make that message read as what the person means (\"Conferma il preventivo per Rossi\"). @OpenUrl opens a web page in a new tab, only with an http(s) URL you actually have.",
	"- Nothing in the block can call Owni, a tool or the network: Query() and Mutation() are not available. Do the work with your tools first, then show the result.",
	"",
	"The language follows.",
].join("\n");

// Not for Owni: made-up data, pictures (they do not load), and a chart for every number (the opening decides).
const rules = openuiChatPromptOptions.additionalRules.filter((rule) => !/realistic\/plausible data|image|Image|Quantitative asks/.test(rule));
// A form with no pictures, in Italian: OpenUI's own form example opens with picture cards.
const form = `Example 3 — Form to collect a request (a compact form, no pictures):

root = Card([header, form])
header = CardHeader("Nuovo preventivo", "Due dettagli e lo preparo")
form = Form("preventivo", formButtons, [fcClient, fcDelivery, fcKind, fcNotes])
formButtons = Buttons([btnSubmit], "row")
btnSubmit = Button("Prepara il preventivo", @ToAssistant("Prepara il preventivo con questi dati"), "primary")
fcClient = FormControl("Cliente", clientInput, "Nome o ragione sociale")
clientInput = Input("cliente", "es. Rossi Srl", "text", { required: true })
fcDelivery = FormControl("Consegna", deliveryPicker)
deliveryPicker = DatePicker("consegna", "single")
fcKind = FormControl("Tipo di lavoro", kindCards)
kindCards = OptionCards("tipo", "single", [oc1, oc2], { required: true })
oc1 = OptionCard("fornitura", "Fornitura", "Solo materiali", oc1icon)
oc1icon = Icon("package", "shopping")
oc2 = OptionCard("posa", "Fornitura e posa", "Materiali e lavoro", oc2icon)
oc2icon = Icon("hammer", "tools")
fcNotes = FormControl("Note", notesArea, "Misure o richieste particolari")
notesArea = TextArea("note", "es. 3 finestre 120x140", 3)`;
const examples = [openuiChatPromptOptions.examples[1], form, openuiChatPromptOptions.examples[4]];
const guide = generateSystemPrompt({ library: openuiChatLibrary.toSpec(), promptOptions: { preamble, additionalRules: rules, examples, toolCalls: false, bindings: false } })
	.split("\n")
	.filter((line) => !line.includes("picsum.photos"))
	.join("\n");

writeFileSync(
	out,
	`// Generated by scripts/openui-guide.mjs from @openuidev/react-ui 0.18.1 and @openuidev/lang-core 1.0.1 (MIT, Thesys Inc.): do not edit by hand.\n\n/** How to write an interactive answer for the console (ADR 0118), read by the agente with openui_guide. */\nexport const OPENUI_GUIDE = ${JSON.stringify(guide)};\n`,
);
console.log(`${out}: ${guide.length} characters`);
